class RISCZDAGToDAGISel : public SelectionDAGISel {
  static char ID;
  const RISCZSubtarget *Subtarget = nullptr;

public:
  RISCZDAGToDAGISel(RISCZTargetMachine &TM, CodeGenOptLevel OptLevel)
      : SelectionDAGISel(TM, OptLevel) {}

  bool runOnMachineFunction(MachineFunction &MF) override {
    Subtarget = &MF.getSubtarget<RISCZSubtarget>();
    return SelectionDAGISel::runOnMachineFunction(MF);
  }

  bool SelectAddrFI(SDValue Addr, SDValue &Base);
  bool SelectBaseAddr(SDValue Addr, SDValue &Base);

  void Select(SDNode *N) override;

// Include the pieces autogenerated from the target description.
#include "RISCZGenDAGISel.inc"
};

class RISCZDAGToDAGISelLegacy : public SelectionDAGISelLegacy {
public:
  static char ID;

  RISCZDAGToDAGISelLegacy(RISCZTargetMachine &TM, CodeGenOptLevel OptLevel)
      : SelectionDAGISelLegacy(
            ID, std::make_unique<RISCZDAGToDAGISel>(TM, OptLevel)){}

  StringRef getPassName() const override {
    return "riscz DAG->DAG Pattern Instruction Selection";
  }
};


/// This pass converts a legalized DAG into a riscz-specific DAG, ready for
/// instruction scheduling.
FunctionPass *createRISCZISelDag(RISCZTargetMachine &TM,
                                  CodeGenOptLevel OptLevel) {
  return new RISCZDAGToDAGISelLegacy(TM, OptLevel);
}

