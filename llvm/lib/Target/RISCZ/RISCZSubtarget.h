#ifndef __LLVM_LIB_TARGET_RISCZ_RISCZSUBTARGET_H__
#define __LLVM_LIB_TARGET_RISCZ_RISCZSUBTARGET_H__

#include "MCTargetDesc/RISCZInfo.h"
#include "RISCZRegisterInfo.h"
#include "RISCZFrameLowering.h"
#include "RISCZISelLowering.h"
#include "RISCZInstrsInfo.h"
#include "llvm/CodeGen/SelectionDAGTargetInfo.h"
#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include <string>

#define GET_SUBTARGETINFO_HEADER
#include "RISCZGenSubtargetInfo.inc"

namespace llvm {

class TargetMachine;

class RISCZSubtarget : public RISCZGenSubtargetInfo {
  virtual void anchor();

  RISCZRegisterInfo RegInfo;
  RISCZInstrInfo InstrInfo;
  RISCZFrameLowering FrameLowering;
  RISCZTargetLowering TLInfo;
  SelectionDAGTargetInfo TSInfo;
  risczABI::ABI TargetABI = risczABI::ABI_LP64;
  MVT XLenVT = MVT::i64;
  unsigned XLen = 64;

public:
  RISCZSubtarget(const Triple &TT, const std::string &CPU, const std::string &FS,
                  const TargetMachine &TM);

  /// Definition of function is auto generated by tblgen.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);

  const RISCZInstrInfo *getInstrInfo() const override { return &InstrInfo; }
  const RISCZFrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }
  const RISCZTargetLowering *getTargetLowering() const override {
    return &TLInfo;
  }
  const RISCZRegisterInfo *getRegisterInfo() const override { return &RegInfo; }
  const SelectionDAGTargetInfo *getSelectionDAGInfo() const override {
    return &TSInfo;
  }

  auto getTargetABI() const { return TargetABI; }
  auto getXLenVT() const { return XLenVT; }
  auto getXLen() const { return XLen; }
};

} // end namespace llvm

#endif // __LLVM_LIB_TARGET_RISCZ_RISCZSUBTARGET_H__